export const BET_ERROR_LABELS: LocaleDict<Dict> = {
  ko, en, ja, es, pt, de, zh, "zh-hant": zhHant, fr, id, ms, hi, tr, vi, ru, ar, it, pl,
};

/** 잘못된 벳 사이즈 결과를 현재 언어 문구로. ar은 입력값만 LTR로 묶는다(호출부가 전체를 autoIso로 감싼다). */
export const betErrorText = (res: BetSanitized, locale: Locale = i18n.locale as Locale): string => {
  if (!res.error) return res.s;
  const { code, input } = res.error;
  const value = locale === "ar" ? ltrIso(input) : input;
  return BET_ERROR_LABELS[locale][code].replace("{v}", value);
};
